#!/usr/bin/env python3
"""Acceptance tests for MP4 edit list ('elst') support in the faad CLI.

Fixtures (generated by gen_fixtures.py, media is a 0.25 s 440 Hz tone,
11025 samples @ 44100 Hz, 12 AAC frames, mdhd duration 12049):

  elst_offset.m4a   edit list: {seg=100, media_time=-1} (empty edit,
                    0.1 s presentation offset), {seg=250, media_time=1024}
  elst_offset_v1.m4a  same timeline, stored as a version-1 (64-bit) elst
  elst_multientry.m4a  {100,-1}, {100,1024}, {100,5434}: empty edit plus
                    two contiguous media entries of 0.1 s each
  elst_trailing.m4a  {100,1024}, {100,-1}: 0.1 s media plus a trailing
                    empty edit (0.1 s of silence at the end)
  elst_gapless.m4a  edit list {seg=200, media_time=2048} AND an iTunSMPB
                    gapless tag (delay=1024, valid=11025) that disagrees
                    with it; the edit list must take precedence
  gapless_only.m4a  no edit list; iTunSMPB delay=1024 valid=11025
  noelst.m4a        no edit list, no gapless tag

  noelst.ref.wav    output of the unmodified (baseline) faad for noelst.m4a;
                    decoding without an edit list must stay bit-identical.

Usage: python3 tests/test_elst.py [path-to-faad-binary]
"""
import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
FIXTURES = os.path.join(HERE, "fixtures")

# --- hardcoded expectations (see fixture descriptions above) ---
OFFSET_SAMPLES = 4410          # 0.1 s empty edit @ 44100 Hz
OFFSET_FIRST_NONZERO = 4410    # media starts right after the empty edit
OFFSET_TOTAL = 15435           # 4410 (empty edit) + 11025 (media)
MULTIENTRY_TOTAL = 13230       # 4410 (empty edit) + 2 x 4410 (media)
MULTIENTRY_MEDIA = 8820        # 2 x 4410
TRAILING_TOTAL = 8820          # 4410 (media) + 4410 (trailing empty edit)
TRAILING_MEDIA = 4410
ELST_GAPLESS_TOTAL = 8820      # seg=200 @ movie timescale 1000 -> 0.2 s
ELST_GAPLESS_TRIM = 1024       # media_time 2048 - 1 frame decoder delay
GAPLESS_ONLY_TOTAL = 11025     # iTunSMPB valid samples
NOELST_TOTAL = 11264           # 11 decodable frames x 1024 (baseline behaviour)

failures = []


def check(name, cond, detail=""):
    print("%s %s %s" % ("PASS" if cond else "FAIL", name, detail))
    if not cond:
        failures.append(name)


def decode(faad, fixture, out):
    r = subprocess.run([faad, "-q", "-o", out, os.path.join(FIXTURES, fixture)],
                       capture_output=True)
    if r.returncode != 0:
        print("FAIL decode %s: %s" % (fixture, r.stderr.decode(errors="replace")))
        failures.append("decode " + fixture)
        return None
    return read_wav(out)


def read_wav(path):
    d = open(path, "rb").read()
    i = d.find(b"data")
    n = struct.unpack("<I", d[i + 4:i + 8])[0]
    return struct.unpack("<%dh" % (n // 2), d[i + 8:i + 8 + n])


def main():
    faad = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        HERE, "..", "build", "faad")

    ref_path = os.path.join(FIXTURES, "noelst.ref.wav")
    ref = read_wav(ref_path)
    check("reference length", len(ref) == NOELST_TOTAL, "got %d" % len(ref))

    with tempfile.TemporaryDirectory() as tmp:
        off = decode(faad, "elst_offset.m4a", os.path.join(tmp, "off.wav"))
        off1 = decode(faad, "elst_offset_v1.m4a", os.path.join(tmp, "off1.wav"))
        mul = decode(faad, "elst_multientry.m4a", os.path.join(tmp, "mul.wav"))
        trl = decode(faad, "elst_trailing.m4a", os.path.join(tmp, "trl.wav"))
        gap = decode(faad, "elst_gapless.m4a", os.path.join(tmp, "gap.wav"))
        gonly = decode(faad, "gapless_only.m4a", os.path.join(tmp, "gonly.wav"))
        noe = decode(faad, "noelst.m4a", os.path.join(tmp, "noe.wav"))
        noe_bytes = open(os.path.join(tmp, "noe.wav"), "rb").read()
    if None in (off, off1, mul, trl, gap, gonly, noe):
        sys.exit(1)

    # 1. fixed edit-list sample: exact output length and start sample
    check("elst_offset length", len(off) == OFFSET_TOTAL,
          "want %d got %d" % (OFFSET_TOTAL, len(off)))
    check("elst_offset leading silence",
          all(v == 0 for v in off[:OFFSET_SAMPLES]))
    first_nonzero = next((k for k, v in enumerate(off) if v != 0), None)
    check("elst_offset start sample", first_nonzero == OFFSET_FIRST_NONZERO,
          "got %r" % first_nonzero)
    check("elst_offset media matches baseline stream",
          tuple(off[OFFSET_SAMPLES:]) == ref[:GAPLESS_ONLY_TOTAL])

    # 1b. version-1 (64-bit) edit list: same timeline
    check("elst_offset_v1 equals v0 output", tuple(off1) == tuple(off))

    # 1c. multiple entries: empty edit + contiguous media entries
    check("elst_multientry length", len(mul) == MULTIENTRY_TOTAL,
          "want %d got %d" % (MULTIENTRY_TOTAL, len(mul)))
    check("elst_multientry leading silence",
          all(v == 0 for v in mul[:OFFSET_SAMPLES]))
    check("elst_multientry media matches baseline stream",
          tuple(mul[OFFSET_SAMPLES:]) == ref[:MULTIENTRY_MEDIA])

    # 1d. trailing empty edit: silence padding at the end
    check("elst_trailing length", len(trl) == TRAILING_TOTAL,
          "want %d got %d" % (TRAILING_TOTAL, len(trl)))
    check("elst_trailing media matches baseline stream",
          tuple(trl[:TRAILING_MEDIA]) == ref[:TRAILING_MEDIA])
    check("elst_trailing trailing silence",
          all(v == 0 for v in trl[TRAILING_MEDIA:]))

    # 2. edit list combined with gapless tag: edit list wins
    check("elst_gapless length", len(gap) == ELST_GAPLESS_TOTAL,
          "want %d got %d" % (ELST_GAPLESS_TOTAL, len(gap)))
    check("elst_gapless is not the iTunSMPB length",
          len(gap) != GAPLESS_ONLY_TOTAL)
    check("elst_gapless content matches baseline stream shifted by trim",
          tuple(gap) == ref[ELST_GAPLESS_TRIM:ELST_GAPLESS_TRIM + ELST_GAPLESS_TOTAL])

    # 3. gapless tag alone still works
    check("gapless_only length", len(gonly) == GAPLESS_ONLY_TOTAL,
          "want %d got %d" % (GAPLESS_ONLY_TOTAL, len(gonly)))
    check("gapless_only content matches baseline stream",
          tuple(gonly) == ref[:GAPLESS_ONLY_TOTAL])

    # 4. no edit list: bit-identical to the baseline output
    check("noelst length", len(noe) == NOELST_TOTAL,
          "want %d got %d" % (NOELST_TOTAL, len(noe)))
    check("noelst bit-identical to baseline",
          noe_bytes == open(ref_path, "rb").read())

    print()
    if failures:
        print("%d failure(s)" % len(failures))
        sys.exit(1)
    print("all tests passed")


if __name__ == "__main__":
    main()
